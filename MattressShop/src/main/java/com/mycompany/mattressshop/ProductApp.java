    private void processSale()
    {
        String customerName = Name_Field.getText().trim();
        String productName = (String) cbx_Product.getSelectedItem();
        String priceText = Price_Field.getText();
        
        if (customerName.isEmpty() || priceText.isEmpty())
            {
                JOptionPane.showMessageDialog(this, "Plese enter a customer name and a product price.", "Missing Information", JOptionPane.WARNING_MESSAGE);
                return;
            }
        
        double productPrice;
        try
        {
            productPrice = Double.parseDouble(priceText);
        }
        catch(NumberFormatException ex)
        {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Invalid Price", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        
        ProductCalculations calculations;
        try
        {
        calculations = new ProductCalculations(productPrice);
        }
        catch(IllegalArgumentException ex)
        {
        JOptionPane.showMessageDialog(this, ex.getMessage(),"Invalid Price", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        
        String message = "Customer Name: " + customerName
            +"\nProduct: " + productName
            +"\nVAT: " + "R" +(calculations.GetVat())
            +"\nCOMMISSION: " + "R" + (calculations.GetCommission())
            +"\nTotal: " + "R" + calculations.GetTotal();
        
        try
        {
            saveToDataFile(customerName, productName, productPrice, calculations);
        }
        catch(IOException ex)
        {
            JOptionPane.showMessageDialog(this, "Unable to save the sales file: " + ex.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        JOptionPane.showMessageDialog(this, message, "Message", JOptionPane.INFORMATION_MESSAGE);
    }
    
    private void saveToDataFile(String customerName, String productName, double productPrice,
                                ProductCalculations calculations) throws IOException
    {
       try (FileWriter writer = new FileWriter("DATA_log.txt"))
            {
            writer.write("DATA LOG\n");
            writer.write("******************************\n");
            writer.write("Customer Name: " + customerName);
            writer.write("\nProduct: " + productName);
            writer.write("\nVAT: " + "R" + calculations.GetVat());
            writer.write("\nCommission: " + "R" + calculations.GetCommission());
            writer.write("\nTotal: " + "R" + calculations.GetTotal());
            writer.write("\n******************************");
            JOptionPane.showMessageDialog(this, "Sales data saved to sales_log.txt");
            }
        catch(IOException exception)
        {
        JOptionPane.showMessageDialog(this, "Could not save the sales file: " + exception.getMessage());
        }
    }
    
